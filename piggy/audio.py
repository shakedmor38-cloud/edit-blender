"""Build the clip soundtrack (song + echoed 'pu' tail) and js/data.js (beat grid + vocal envelope)."""
import json
from pathlib import Path
import numpy as np, librosa, soundfile as sf

HERE = Path(__file__).parent
SR, FPS = 48000, 60
y, _ = librosa.load(HERE / "assets/song.wav", sr=SR, mono=False)
n = y.shape[1]; dur = n / SR

# the song is cut mid-'pu': soften the cut, then echo the last 'pu' on the next three beats
BEAT = 0.3691
y[:, -int(.012 * SR):] *= np.linspace(1, 0, int(.012 * SR))
pu = y[:, int(7.86 * SR):].copy()
fade = np.ones(pu.shape[1]); k = int(.01 * SR); fade[:k] = np.linspace(0, 1, k); fade[-k:] = np.linspace(1, 0, k)
pu *= fade
tail = 1.55
out = np.zeros((2, n + int(tail * SR)), np.float32); out[:, :n] = y
for i, g in enumerate([.42, .24, .12], 1):
    s = int((7.86 + i * BEAT) * SR); seg = pu * g
    # ping-pong the echoes left/right
    pan = (1.0, .55) if i % 2 else (.55, 1.0)
    out[0, s:s + seg.shape[1]] += seg[0] * pan[0]; out[1, s:s + seg.shape[1]] += seg[1] * pan[1]
# light reverb wash under the tail (decaying noise convolution)
ir_t = np.arange(int(1.2 * SR)) / SR
rng = np.random.default_rng(3)
ir = rng.standard_normal(len(ir_t)) * np.exp(-ir_t * 4.5) * .02
wet_in = out.copy(); wet_in[:, :int(7.6 * SR)] = 0
from scipy.signal import fftconvolve
wet = np.stack([fftconvolve(wet_in[c], ir)[:out.shape[1]] for c in range(2)])
out += wet
end = out.shape[1]; f = int(.35 * SR); out[:, end - f:] *= np.linspace(1, 0, f) ** 2
out /= max(1.0, np.abs(out).max() / .97)
sf.write(HERE / "out/audio.wav", out.T, SR, subtype="PCM_24")
TOTAL = out.shape[1] / SR

# vocal envelope (harmonic part, 300-3000 Hz), FPS values per second
mono = librosa.to_mono(out)
yh, _ = librosa.effects.hpss(librosa.resample(mono, orig_sr=SR, target_sr=22050), margin=2)
hop = 22050 // FPS
S = np.abs(librosa.stft(yh, n_fft=1024, hop_length=hop)); fr = librosa.fft_frequencies(sr=22050, n_fft=1024)
band = S[(fr > 300) & (fr < 3000)].sum(0)
band = np.convolve(band, np.ones(3) / 3, "same")
band = np.clip((band / np.percentile(band, 97) - .12) / .88, 0, 1)
# overall loudness for beat-reactive glow
rms = librosa.feature.rms(y=librosa.resample(mono, orig_sr=SR, target_sr=22050), hop_length=hop)[0]
rms = np.clip(rms / np.percentile(rms, 98), 0, 1)

# beat grid fitted to librosa's tracked beats
_, bt = librosa.beat.beat_track(y=librosa.resample(mono[:n], orig_sr=SR, target_sr=22050), sr=22050, units="time")
bt = bt[bt > .9]; idx = np.round((bt - bt[0]) / BEAT)
a, b = np.polyfit(idx, bt, 1)
beat0 = b - a * np.ceil(b / a)
data = dict(total=round(TOTAL, 3), songEnd=round(dur, 3), beat=round(float(a), 5), beat0=round(float(beat0), 4),
            fps=FPS, voc=[round(float(v), 2) for v in band], rms=[round(float(v), 2) for v in rms])
(HERE / "js/data.js").write_text("// generated by audio.py\nconst DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
print("total", TOTAL, "beat", a, "beat0", beat0, "frames", len(band))
